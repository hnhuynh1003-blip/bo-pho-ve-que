// B1 S1 dynamic sign component: never mutate saves or show a sign for draft art.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const src=fs.readFileSync(new URL('../js/v88-shop-sign.js',import.meta.url),'utf8');
const window={};
vm.runInNewContext(src,{window},{filename:'v88-shop-sign.js'});
const sign=window.BPVQShopSignV88;
assert.ok(sign,'sign component must be registered');
const good={id:'boba-b1',career:'boba',tier:1,isReady:true,anchors:{S1:{x:.505,y:.373,layer:4}}};
const draft={...good,isReady:false};
const before=JSON.stringify(good);
assert.equal(sign.render(draft,'Quán Ngọc'),'', 'draft art must not display an approved dynamic plaque');
assert.equal(sign.validS1(draft),null);
assert.equal(sign.render({...good,anchors:{}},'Quán Ngọc'),'','S1 anchor is required');
assert.equal(sign.render({...good,anchors:{S1:{x:3,y:.2,layer:1}}},'Quán Ngọc'),'','anchor must stay in 0..1');
assert.equal(sign.render({...good,anchors:{S1:{x:.3,y:.2,layer:99}}},'Quán Ngọc'),'','layer must stay valid');
const built=sign.render(good,'Trà Sữa Bé Thỏ');
assert.ok(built.includes('Trà Sữa Bé Thỏ'));
assert.ok(built.includes('data-v88-shop-sign="S1"'));
assert.ok(built.includes('left:50.5%'));
assert.ok(built.includes('top:37.3%'));
assert.ok(built.includes('z-index:4'));
assert.equal(JSON.stringify(good),before,'render must never change scene record');
assert.equal(sign.normalizeName('', 'boba'),'Quán Trà Sữa');
assert.equal(sign.normalizeName('', 'noodle'),'Quán Mì Cay');
assert.equal(sign.normalizeName('   ', 'streetfood'),'Quán Xiên Que');
const malicious='"><img src=x onerror=alert(1)>';
const clean=sign.render(good,malicious);
assert.ok(clean.includes('&lt;img'),'HTML tag must be escaped');
assert.ok(!clean.includes('<img'),'script injection must not enter markup');
assert.ok(!clean.includes('onerror=alert(1)>'),'unescaped handler must not enter markup');
assert.ok(clean.length<800,'sign should not grow without limit');
const long=sign.normalizeName('X'.repeat(60),'boba');
assert.equal(long.length,32,'sign name must be bounded');
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const phone=fs.readFileSync(new URL('../js/phone-os-v88.js',import.meta.url),'utf8');
const css=fs.readFileSync(new URL('../css/phone-os-v88.css',import.meta.url),'utf8');
assert.ok(html.includes('src="js/v88-shop-sign.js?'),'dynamic sign must load in actual game HTML');
assert.ok(html.indexOf('src="js/v88-shop-sign.js?')>html.indexOf('src="js/v88-shop-scenes.js?'),'sign should load after scene registry');
assert.ok(phone.includes("filter(([slot])=>slot!=='S1')"),'S1 must not render both a sign and a slot badge');
assert.ok(phone.includes('w.BPVQShopSignV88?.render(scene,s.shopName)'),'sign must use player profile shop name');
assert.ok(css.includes('.v88-arch-shop-sign'),'dynamic sign CSS missing');
assert.ok(css.includes('.v88-arch-scene img{display:block;width:100%;height:auto;object-fit:contain}'),'approved shells must keep their natural aspect ratio for anchor alignment');
console.log('V88 S1 SIGN: approved shell only, real player name, HTML escaping, 32-char limit, coordinate contract PASS');
