// Verify batch QA is reusable and cannot silently mark concept art as approved.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'bpvq-art-v88-'));
try{
 const source=path.join(temp,'sources'),out=path.join(temp,'qa');
 fs.mkdirSync(source);
 const assets=path.resolve('assets/images');
 const realWebp=fs.readdirSync(assets).find(n=>n.toLowerCase().endsWith('.webp'));
 assert.ok(realWebp,'repository must have at least one real WebP to test');
 const real=fs.readFileSync(path.join(assets,realWebp));
 for(const num of ['01','09'])fs.writeFileSync(path.join(source,'TRA_SUA_B'+num+'_PREVIEW.webp'),real);
 const invoke=(dest)=>spawnSync(process.execPath,['scripts/v88-batch-art.mjs','--source-dir',source,'--out-dir',dest],{encoding:'utf8'});
 const run=invoke(out);
 assert.equal(run.status,0,run.stderr||run.stdout);
 const {summary,entries}=JSON.parse(fs.readFileSync(path.join(out,'qa_manifest.json'),'utf8'));
 assert.equal(summary.total,27);
 assert.equal(summary.found,2);
 assert.equal(summary.missing,25);
 assert.equal(summary.invalid,0);
 assert.equal(summary.productionReady,0);
 assert.equal(summary.reviewOnly,true);
 assert.deepEqual(summary.stageSlotCounts,[6,9,11,14,16,18,20,22,24]);
 assert.deepEqual(summary.batches.map(x=>x.found),[1,0,1]);
 assert.equal(entries.length,27);
 assert.equal(new Set(entries.map(x=>x.id)).size,27);
 const b1=entries.find(x=>x.id==='boba-b1');
 assert.equal(b1.status,'concept-only');
 assert.equal(b1.approval,'pending');
 assert.equal(b1.productionReady,false);
 assert.equal(b1.slotCount,6);
 assert.equal(b1.preview,'concepts/boba-b1-concept.webp');
 assert.ok(b1.sha256&&b1.sha256.length===64);
 assert.ok(b1.dimensions?.width>0&&b1.dimensions?.height>0);
 assert.ok(fs.readFileSync(path.join(out,b1.preview)).equals(real),'concept bytes must be preserved exactly');
 const b9=entries.find(x=>x.id==='boba-b9');
 assert.ok(b9.reviewNote.includes('CONCEPT CŨ MÁI ĐỎ'));
 assert.equal(b9.productionReady,false);
 assert.equal(b9.slotCount,24);
 const missing=entries.find(x=>x.id==='noodle-b1');
 assert.equal(missing.status,'missing');
 assert.equal(missing.preview,null);
 assert.equal(missing.productionReady,false);
 assert.equal(entries.find(x=>x.id==='streetfood-b9').status,'missing');
 const html=fs.readFileSync(path.join(out,'index.html'),'utf8');
 assert.ok(html.includes('Chỉ dùng để duyệt'));
 assert.ok(html.includes('Ảnh B9 cũ không phải thiết kế mới'));
 assert.ok(!html.includes('concepts/noodle-b1-concept.webp'),'never create broken links for missing assets');
 assert.ok(!fs.existsSync(path.join(out,'shops')),'never generate an approved shop asset tree');
 const csv=fs.readFileSync(path.join(out,'qa_board.csv'),'utf8');
 assert.equal(csv.trim().split('\n').length,28);
 // A duplicate legacy basename must be rejected, not chosen arbitrarily.
 fs.mkdirSync(path.join(source,'duplicate'));
 fs.copyFileSync(path.join(source,'TRA_SUA_B01_PREVIEW.webp'),path.join(source,'duplicate','TRA_SUA_B01_PREVIEW.webp'));
 const out2=path.join(temp,'duplicates');
 const second=invoke(out2);
 assert.equal(second.status,0,second.stderr);
 const data2=JSON.parse(fs.readFileSync(path.join(out2,'qa_manifest.json'),'utf8'));
 assert.equal(data2.summary.invalid,1);
 assert.equal(data2.summary.found,1);
 assert.equal(data2.entries.find(x=>x.id==='boba-b1').status,'invalid-input');
 assert.ok(data2.entries.find(x=>x.id==='boba-b1').issues[0].includes('Trùng tên'));
 console.log('BATCH ART 27: 3 careers × 9 stages, QA board, original hashes, no fake approvals, duplicate handling PASS');
}finally{fs.rmSync(temp,{recursive:true,force:true})}
